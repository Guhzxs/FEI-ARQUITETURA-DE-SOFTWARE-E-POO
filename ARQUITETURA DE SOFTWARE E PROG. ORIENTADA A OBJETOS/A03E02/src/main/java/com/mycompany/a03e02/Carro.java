
package com.mycompany.a03e02;


public class Carro {
    private String modelo, cor;
    private int ano, km;
    private double preco;
    
    public Carro(){
        
    }
    
    public String getModelo(){
        return modelo;
    }
    
    public String getCor(){
        return cor;
    }
    
    public int getAno(){
        return ano;
    }
    
    public double getPreco(){
        return preco;
    }
    
    public int getKm(){
        return km;
    }
    
    
}
